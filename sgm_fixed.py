"""Fixed SGM pattern set: coefficient maps rendered from a parameter CSV + manifest.

The CSV is the dataset (one row per Gaussian component, keyed by pattern_id and
component). The manifest carries the render spec (canvas, threshold, postprocess)
and the CSV sha256, which is checked at load. Rendering is deterministic, so every
run and seed sees the same maps in the same order. The set is generated by a
separate script that is not part of this repository.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path
from typing import Iterator, Tuple

import numpy as np
from xflow.data import build_transforms_from_config
from xflow.extensions.physics import pattern_gen

PARAM_COLS = ("intensity", "std_x_px", "std_y_px", "rotation_rad", "dx_px", "dy_px")


def _make_canvas(manifest: dict) -> pattern_gen.DynamicPatterns:
    spec = manifest["canvas"]
    canvas = pattern_gen.DynamicPatterns(spec["height"], spec["width"])
    canvas.set_max_pixel_value(spec["max_pixel_value"])
    canvas.set_postprocess_fns(
        build_transforms_from_config(manifest["process_functions"])
    )
    canvas.set_threshold(spec["minimum_pixel_threshold"])
    return canvas


def _render(canvas: pattern_gen.DynamicPatterns, rows: list) -> np.ndarray:
    """One pattern from its component rows [intensity, std_x, std_y, rotation, dx, dy] (pixels)."""
    canvas.clear_canvas()
    canvas._distributions = [
        pattern_gen.StaticGaussianDistribution(canvas) for _ in rows
    ]
    for dst, (intensity, sx, sy, rot, dx, dy) in zip(canvas._distributions, rows):
        dst.intensity, dst.std_x, dst.std_y = intensity, sx, sy
        dst.rotation, dst.dx, dst.dy = rot, dx, dy
        dst._pattern = dst.pattern_generation()
    canvas.apply_distribution()
    return canvas.get_image()


def load_fixed_set(csv_path, manifest_path, first_n=None) -> Tuple[np.ndarray, dict]:
    """Render the set (or its first `first_n` patterns). Returns (maps[N, h, w] float32
    in pattern_id order, manifest)."""
    csv_path, manifest_path = Path(csv_path), Path(manifest_path)
    manifest = json.loads(manifest_path.read_text())
    sha = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    if sha != manifest["csv"]["sha256"]:
        raise ValueError(
            f"{csv_path.name} does not match the manifest sha256; the set was altered"
        )
    params: dict = {}
    with csv_path.open(newline="") as f:
        for r in csv.DictReader(f):
            params.setdefault(int(r["pattern_id"]), []).append(
                [float(r[k]) for k in PARAM_COLS]
            )
    ids = sorted(params)
    if ids != list(range(len(ids))) or len(ids) != int(manifest["n_patterns"]):
        raise ValueError("pattern_id must run 0..n_patterns-1 without gaps")
    if first_n is not None:
        first_n = int(first_n)
        if not 0 < first_n <= len(ids):
            raise ValueError(f"first_n must be in 1..{len(ids)}, got {first_n}")
        ids = ids[:first_n]
    canvas = _make_canvas(manifest)
    maps = np.stack([_render(canvas, params[i]) for i in ids]).astype(np.float32)
    # The manifest statistics describe the full set only.
    stats = manifest.get("map_stats", {}) if first_n is None else {}
    zero = int((maps.reshape(len(ids), -1).sum(1) == 0).sum())
    if "all_zero_maps" in stats and zero != int(stats["all_zero_maps"]):
        raise ValueError("rendered set disagrees with manifest map_stats.all_zero_maps")
    if "max_value" in stats and not np.isclose(float(maps.max()), stats["max_value"], atol=1e-6):
        raise ValueError("rendered set disagrees with manifest map_stats.max_value")
    return maps, manifest


def fixed_pattern_stream(csv_path, manifest_path, first_n=None) -> Iterator[np.ndarray]:
    """Infinite generator over the set (or its first `first_n` patterns) in pattern_id
    order, cycling; a pattern_provider for SpatialNearestCombinator. One epoch of
    num_samples = number of patterns used is one pass."""
    maps, manifest = load_fixed_set(csv_path, manifest_path, first_n)
    print(
        f"[sgm_fixed] {manifest['name']}: using {len(maps)} of {manifest['n_patterns']} "
        f"patterns {tuple(maps.shape[1:])} "
        f"from {Path(csv_path).name} (sha256 {manifest['csv']['sha256'][:12]})"
    )
    while True:
        for m in maps:
            yield m
